export class I18nManager {
  constructor() {
    this.storageKey = 'top_sudoku_lang';
    this.currentLang = this.detectLanguage();
    this.modal = null;
  }

  detectLanguage() {
    // 1. URL parameter ?lang=
    try {
      const urlParams = new URLSearchParams(window.location.search);
      const urlLang = (urlParams.get('lang') || '').toLowerCase();
      if (urlLang && I18N_LANGUAGES[urlLang]) return urlLang;
    } catch (e) {}

    // 2. LocalStorage
    try {
      const saved = localStorage.getItem(this.storageKey);
      if (saved && I18N_LANGUAGES[saved]) return saved;
    } catch (e) {}

    // 3. Browser navigator language
    const navLang = (navigator.language || navigator.userLanguage || 'es').split('-')[0].toLowerCase();
    if (I18N_LANGUAGES[navLang]) return navLang;

    return 'es';
  }

  setLanguage(lang) {
    if (!I18N_LANGUAGES[lang]) return;
    this.currentLang = lang;
    try {
      localStorage.setItem(this.storageKey, lang);
    } catch (e) {}

    this.applyTranslations();

    if (window.sudokuApp && typeof window.sudokuApp.onLanguageChanged === 'function') {
      window.sudokuApp.onLanguageChanged(lang);
    }
  }

  t(key, params = {}) {
    const dict = I18N_TRANSLATIONS[this.currentLang] || I18N_TRANSLATIONS.es;
    let text = dict[key] || I18N_TRANSLATIONS.es[key] || key;

    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.split('{' + pKey + '}').join(pVal);
    }
    return text;
  }

  init() {
    this.modal = document.getElementById('modal-language');
    this.bindEvents();
    this.applyTranslations();
  }

  bindEvents() {
    const openBtn = document.getElementById('btn-open-lang-modal');
    const closeBtn = document.getElementById('btn-close-lang-modal');

    if (openBtn) {
      openBtn.addEventListener('click', () => this.openModal());
    }
    if (closeBtn) {
      closeBtn.addEventListener('click', () => this.closeModal());
    }

    if (this.modal) {
      this.modal.addEventListener('click', (e) => {
        if (e.target === this.modal) this.closeModal();
      });
    }

    // Language cards click
    document.querySelectorAll('.lang-card').forEach(card => {
      card.addEventListener('click', () => {
        const lang = card.getAttribute('data-lang');
        if (lang) {
          this.setLanguage(lang);
          this.closeModal();
        }
      });
    });

    window.addEventListener('keydown', (e) => {
      if (e.key === 'Escape' && this.modal && !this.modal.classList.contains('hidden')) {
        this.closeModal();
      }
    });
  }

  openModal() {
    if (!this.modal) return;
    this.updateActiveCard();
    this.modal.classList.remove('hidden');
  }

  closeModal() {
    if (!this.modal) return;
    this.modal.classList.add('hidden');
  }

  updateActiveCard() {
    document.querySelectorAll('.lang-card').forEach(card => {
      const isCurrent = card.getAttribute('data-lang') === this.currentLang;
      if (isCurrent) {
        card.classList.add('ring-2', 'ring-amber-400', 'bg-slate-800');
        card.classList.remove('bg-slate-900/60');
      } else {
        card.classList.remove('ring-2', 'ring-amber-400', 'bg-slate-800');
        card.classList.add('bg-slate-900/60');
      }
    });
  }

  applyTranslations() {
    // 1. Textos con data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation && translation !== key) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    // 2. Tooltips y títulos con data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translation = this.t(key);
      if (translation && translation !== key) {
        el.title = translation;
      }
    });

    // 3. Placeholders con data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation && translation !== key) {
        el.placeholder = translation;
      }
    });

    // 4. Actualizar botón en cabecera
    const langBtnText = document.getElementById('current-lang-code');
    const langInfo = I18N_LANGUAGES[this.currentLang];
    if (langBtnText && langInfo) {
      langBtnText.textContent = `${langInfo.flag} ${langInfo.name}`;
    }

    // 5. Atributo lang en <html>
    document.documentElement.lang = this.currentLang;

    // 6. Actualizar tarjeta activa en el modal
    this.updateActiveCard();

    // 7. Sincronizar footer y promo si existen
    if (window.sudokuApp && window.sudokuApp.arenaPromo) {
      window.sudokuApp.arenaPromo.customLang = this.currentLang;
      window.sudokuApp.arenaPromo.updateFooterLink();
    }
  }
}

// Instancia global
window.i18n = new I18nManager();
