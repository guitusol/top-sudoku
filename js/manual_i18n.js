function setManualLanguage(lang) {
  if (!MANUAL_I18N[lang]) lang = 'es';
  try {
    localStorage.setItem('top_sudoku_lang', lang);
  } catch (e) {}

  const dict = MANUAL_I18N[lang] || MANUAL_I18N.es;

  // Actualizar textos con data-m-i18n
  document.querySelectorAll('[data-m-i18n]').forEach(el => {
    const key = el.getAttribute('data-m-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Actualizar botones activos de idioma
  document.querySelectorAll('.manual-lang-btn').forEach(btn => {
    const isCurrent = btn.getAttribute('data-lang') === lang;
    if (isCurrent) {
      btn.classList.add('bg-amber-100', 'text-amber-900', 'border-amber-400');
      btn.classList.remove('bg-white', 'text-slate-700');
    } else {
      btn.classList.remove('bg-amber-100', 'text-amber-900', 'border-amber-400');
      btn.classList.add('bg-white', 'text-slate-700');
    }
  });

  document.documentElement.lang = lang;
}

document.addEventListener('DOMContentLoaded', () => {
  // Detectar idioma guardado o por parámetro ?lang=
  let initialLang = 'es';
  try {
    const params = new URLSearchParams(window.location.search);
    const pLang = (params.get('lang') || '').toLowerCase();
    if (pLang && MANUAL_I18N[pLang]) {
      initialLang = pLang;
    } else {
      const saved = localStorage.getItem('top_sudoku_lang');
      if (saved && MANUAL_I18N[saved]) initialLang = saved;
      else {
        const nav = (navigator.language || '').split('-')[0].toLowerCase();
        if (MANUAL_I18N[nav]) initialLang = nav;
      }
    }
  } catch (e) {}

  // Enlazar botones
  document.querySelectorAll('.manual-lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      if (lang) setManualLanguage(lang);
    });
  });

  setManualLanguage(initialLang);
});
